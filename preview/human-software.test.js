const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx=vm.createContext({window:{},console});
for(const name of ['assets/human-data.js','garment-preview.js','human-viewer.js','human-software.js'])vm.runInContext(fs.readFileSync(`${__dirname}/${name}`,'utf8'),ctx);
const r=ctx.window.renderHumanSoftware,v=ctx.window.humanPreviewModel.defaults;
const front=r(v,'waist');
assert(front.includes('человеческая модель'));
assert(!front.includes('NaN'));
for(const key of ['height','bust','waist','hip','hipheight'])assert.notEqual(front,r({...v,[key]:v[key]+10},key),key);
assert.notEqual(front,r(v,'waist',{},'side'));
assert.notEqual(front,r(v,'waist',{},'back'));
// No WebGL library: mounting must still show the SAME human mesh, not a cartoon.
const container={dataset:{},style:{},innerHTML:''};
assert(ctx.window.mountHumanMannequin(container,v,'waist',{}));
assert(container.innerHTML.includes('человеческая модель'));
const previous=container.innerHTML;
ctx.window.setMannequinView('side');
assert.notEqual(container.innerHTML,previous);
const side=container.innerHTML;
const event={pointerId:1,button:0,clientX:10,clientY:10,preventDefault(){}};
container.onpointerdown(event);
container.onpointermove({...event,clientX:45,clientY:30});
assert.notEqual(container.innerHTML,side,'drag rotates in two axes');
container.onpointerup();
const rotated=container.innerHTML;
container.onwheel({deltaY:-200,preventDefault(){}});
assert.notEqual(container.innerHTML,rotated,'wheel zooms');
container.ondblclick();
assert.equal(container.innerHTML,front,'double click resets camera');
console.log('CPU human mesh: all measurements, three views and WebGL-free mounting OK');
let deformations=0;
const deform=ctx.window.humanPreviewModel.deform;
ctx.window.humanPreviewModel.deform=(...args)=>{deformations++;return deform(...args);};
r({...v,waist:73},'waist');
deformations=0;
let triangles=0;
const context={setTransform(){},clearRect(){},beginPath(){triangles++;},moveTo(){},lineTo(){},closePath(){},fill(){},fillText(){}};
r({...v,waist:73},'waist',{},'side',{width:540,height:548,getContext:()=>context});
assert.equal(deformations,0,'rotation must reuse deformed vertices');
assert(triangles>100,'canvas draws the human mesh');
const frames=[];ctx.window.requestAnimationFrame=fn=>frames.push(fn);
let draws=0;const orbit={yaw:0,pitch:0,zoom:1};
ctx.window.bindHumanOrbit(container,orbit,()=>draws++);
container.onpointerdown(event);
for(let i=0;i<20;i++)container.onpointermove({...event,clientX:10+i});
assert.equal(frames.length,1,'pointer events coalesce into one frame');
assert.equal(draws,0);frames.shift()();assert.equal(draws,1);
console.log('Orbit performance: cached deformation, canvas mesh and frame coalescing OK');